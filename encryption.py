def AES(plaintext, key=b"abcdefghijklmnop", num_of_rounds=10):
    #AES-128 so has 10 rounds
    plaintext = plaintext.encode('utf-8')
    blocks = split_to_blocks(plaintext, 128)
    round_keys = expand_round_keys(key)
    ciphertext = []

    for block in blocks:

        state = add_round_key(block, round_keys[0])
        for round in range(1, num_of_rounds):
            state = sub_bytes(state)
            state = shift_rows(state)
            state = mix_columns(state)
            state = add_round_key(state, round_keys[round])

        state = sub_bytes(state)
        state = shift_rows(state)
        state = add_round_key(state, round_keys[num_of_rounds])
        ciphertext.append(state)

    return b''.join(ciphertext).hex()

def AES_decrypt(ciphertext, key=b"abcdefghijklmnop", num_of_rounds=10):
    #Reverse of AES subroutine
    ciphertext = bytes.fromhex(ciphertext)
    blocks = split_to_blocks(ciphertext, 128)
    round_keys = expand_round_keys(key)
    plaintext = []

    for block in blocks:

        state = add_round_key(block, round_keys[num_of_rounds])
        state = inv_shift_rows(state)
        state = inv_sub_bytes(state)

        for round in range(num_of_rounds - 1, 0, -1):
            state = add_round_key(state, round_keys[round])
            state = inv_mix_columns(state)
            state = inv_shift_rows(state)
            state = inv_sub_bytes(state)

        state = add_round_key(state, round_keys[0])
        plaintext.append(state)

    decrypted_bytes = b''.join(plaintext).rstrip(b'\x00')
    return decrypted_bytes.decode('utf-8')

def split_to_blocks(data, block_size):
    if isinstance(data, str):
        data = data.encode('utf-8')
        #Convert to binary 

    while len(data) % (block_size // 8) != 0:
        data += b'\x00'
        #Pad to fit with block size

    block_length = block_size // 8
    return [data[i:i + block_length] for i in range(0, len(data), block_length)]

def expand_round_keys(key):
    #Creates individual round keys for each round
    Nk = 4  #128-bit key so 4 32 bit words (key)
    Nr = 10 #Number of rounds
    Nb = 4 #Number of Columns

    w = [0] * (Nb * (Nr + 1))  # 44 words total for 10 rounds and one final
    Rcon = [0x00,0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1B,0x36] #Constants for the key expansion

    def sub_word(word):
        return [S_BOX[b] for b in word]
    
    def rotate_word(word): 
        return word[1:] + word[:1]

    for i in range(Nk):
        w[i] = [key[4*i], key[4*i+1], key[4*i+2], key[4*i+3]]

    #Generate words for all round keys
    for i in range(Nk, Nb*(Nr+1)):
        temp = w[i-1].copy()
        if i % Nk == 0:
            temp = sub_word(rotate_word(temp))
            temp[0] ^= Rcon[i//Nk]
        w[i] = [w[i - Nk][j] ^ temp[j] for j in range(len(temp))]

    expanded = []
    for wi in w:
        expanded.extend(wi)
    round_keys = [bytes(expanded[i*16:(i+1)*16]) for i in range(Nr+1)]

    return round_keys

def add_round_key(block, round_key):
    #XORs current state with round key
    xorred = []

    for i in range(len(block)):
        xorred.append(block[i] ^ round_key[i])


    return bytes(xorred)

def sub_bytes(state):
    #Substitute bytes in the state using the S-Box
    sbytes = []

    for b in state:
        sbytes.append(S_BOX[b])

    return bytes(sbytes)

def inv_sub_bytes(state):
    #Substitute bytes in the state using the Inverse S-Box
    sbytes = []

    for b in state:
        sbytes.append(INV_S_BOX[b])

    return bytes(sbytes)

def shift_rows(state):
    #Shifts rows in the state (in matrix form) left

    matrix = [list(state[i::4]) for i in range(4)]

    for i in range(4):
        matrix[i] = matrix[i][i:] + matrix[i][:i]
    result = []

    for i in range(4):
        result.extend(matrix[j][i] for j in range(4))

    return bytes(result)

def inv_shift_rows(state):
    #Shifts rows in the state (in matrix form) right

    matrix = [list(state[i::4]) for i in range(4)]

    for i in range(4):
        matrix[i] = matrix[i][-i:] + matrix[i][:-i]
    result = []

    for i in range(4):
        result.extend(matrix[j][i] for j in range(4))

    return bytes(result)

def xtime(a):
    #Multiplication by 2 in GF(2^8)

    return ((a << 1) & 0xff) ^ (0x1b if a & 0x80 else 0x00)

def mix_single_column(col):
    #Mixes one 4-byte column

    temp = col[0] ^ col[1] ^ col[2] ^ col[3]

    u = col[0]

    col[0] ^= temp ^ xtime(col[0] ^ col[1])
    col[1] ^= temp ^ xtime(col[1] ^ col[2])
    col[2] ^= temp ^ xtime(col[2] ^ col[3])
    col[3] ^= temp ^ xtime(col[3] ^ u)

    return col

def mix_columns(state):
    #Mixes all 4 columns using mix single column

    state = list(state)

    for i in range(4):
        col = state[i*4:(i+1)*4]
        mixed = mix_single_column(col)
        state[i*4:(i+1)*4] = mixed

    return bytes(state)

def inv_mix_single_column(col):
    #Inverse of mix single column that uses GF(2^8) matrix multiplication
    def matrix_mul(x, y):
        r = 0
        for i in range(8):
            if y & 1:
                r ^= x
            hi_bit_set = x & 0x80
            x = (x << 1) & 0xff
            if hi_bit_set:
                x ^= 0x1b
            y >>= 1
        return r
    a = col
    return [
        matrix_mul(a[0], 0x0e) ^ matrix_mul(a[1], 0x0b) ^ matrix_mul(a[2], 0x0d) ^ matrix_mul(a[3], 0x09),
        matrix_mul(a[0], 0x09) ^ matrix_mul(a[1], 0x0e) ^ matrix_mul(a[2], 0x0b) ^ matrix_mul(a[3], 0x0d),
        matrix_mul(a[0], 0x0d) ^ matrix_mul(a[1], 0x09) ^ matrix_mul(a[2], 0x0e) ^ matrix_mul(a[3], 0x0b),
        matrix_mul(a[0], 0x0b) ^ matrix_mul(a[1], 0x0d) ^ matrix_mul(a[2], 0x09) ^ matrix_mul(a[3], 0x0e)]

def inv_mix_columns(state):
    #Mixes all 4 columns using inverse mix single column

    state = list(state)
    for i in range(4):
        col = state[i*4:(i+1)*4]
        mixed = inv_mix_single_column(col)
        state[i*4:(i+1)*4] = mixed
    return bytes(state)

